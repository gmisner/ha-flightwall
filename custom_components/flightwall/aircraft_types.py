def type_name(code: str | None, model: str | None = None) -> str:
    """Prefer a real model string, then a known ICAO type name, then the code."""
    if model and str(model).strip() not in {"", "None", "none", "null", "N/A"}:
        return str(model).strip()
    key = str(code or "").strip().upper()
    if not key:
        return ""
    return ICAO_TYPES.get(key, key)
